"""Tracked record of how the shipped model artifacts were produced.

Model binaries and metric JSONs live in ``data/models/`` and are never
committed. ``models/manifest.json`` is: each producing command (training and
both backtests) records its own section with the command and configuration,
code revision, feature schema, data cutoffs, fingerprints of the cached
source snapshots it read, SHA-256 hashes of what it wrote, and its metrics
with their baselines. Serving verifies the hashes against the artifacts it
actually loads, and the README metrics table is rendered from this record.

    uv run python -m nba_insights.ml.manifest backfill   # record existing artifacts
    uv run python -m nba_insights.ml.manifest readme     # re-render the README table
    uv run python -m nba_insights.ml.manifest readme --check
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from datetime import UTC, datetime
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path
from typing import Any

import pandas as pd

from nba_insights.analysis import PLAYER_FORECAST_VERSION
from nba_insights.config import MANIFEST_PATH, MODELS_DIR
from nba_insights.ml.features import OUTCOME_FEATURES, POINTS_FEATURES
from nba_insights.ml.performance import MIN_FEATURES, RATE_FEATURES
from nba_insights.store import Cache

SCHEMA_VERSION = "model-manifest-v1"

# One place for the version labels the registry, manifest, and README share.
MODEL_VERSIONS = {
    "outcome": "logistic-outcome-v1",
    "player_points": "player-points-v1",
    "lineup": "lineup-blend-v1",
    "score_simulator": "matchup-simulator-v1",
    "season_forecast": "season-forecast-v2-roster",
    "player_season": PLAYER_FORECAST_VERSION,
}

# Which files each producing run writes into MODELS_DIR.
RUN_ARTIFACTS = {
    "train": ["outcome.joblib", "points.joblib", "win_curve.joblib", "metrics.json"],
    "season_backtest": ["season_forecast_metrics.json"],
    "player_backtest": ["player_season_metrics.json"],
}

README_COMMAND = "uv run python -m nba_insights.ml.manifest readme"
README_START = f"<!-- model-metrics:start (generated by `{README_COMMAND}`) -->"
README_END = "<!-- model-metrics:end -->"


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def feature_schema() -> dict[str, Any]:
    """Feature lists the trained models consume, with a fingerprint over all of them."""
    schema = {
        "outcome": list(OUTCOME_FEATURES),
        "points": list(POINTS_FEATURES),
        "points_minutes": list(MIN_FEATURES),
        "points_rate": list(RATE_FEATURES),
    }
    payload = json.dumps(schema, sort_keys=True).encode()
    return {"fingerprint": _sha256(payload)[:16], **schema}


def artifact_feature_schema(models_dir: Path = MODELS_DIR) -> dict[str, Any]:
    """Feature lists read back from saved pipelines, compared with the current code."""
    import joblib

    try:
        outcome = joblib.load(models_dir / "outcome.joblib")
        points = joblib.load(models_dir / "points.joblib")
        saved = {
            "outcome": list(outcome.feature_names_in_),
            "points_minutes": list(points["minutes"].feature_names_in_),
            "points_rate": list(points["rate"].feature_names_in_),
        }
    except (OSError, KeyError, AttributeError, TypeError):
        return {"status": "not_recorded", "reason": "saved pipelines expose no feature names"}
    current = feature_schema()
    return {
        "source": "read from saved artifacts",
        "matches_code": all(saved[name] == current[name] for name in saved),
        "code_fingerprint": current["fingerprint"],
        **saved,
    }


def code_identity() -> dict[str, Any]:
    """Package version and, when run from a checkout, the git commit and dirtiness."""
    try:
        package = version("nba-insights")
    except PackageNotFoundError:
        package = None
    commit = dirty = None
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
        status = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=no"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        dirty = bool(status.strip())
    except (OSError, subprocess.CalledProcessError):
        pass
    return {"package_version": package, "git_commit": commit, "git_dirty": dirty}


def artifact_records(names: list[str], models_dir: Path = MODELS_DIR) -> dict[str, Any]:
    """SHA-256 and size per artifact; a missing file is recorded as missing."""
    records: dict[str, Any] = {}
    for name in names:
        path = models_dir / name
        if path.exists():
            data = path.read_bytes()
            records[name] = {"sha256": _sha256(data), "bytes": len(data)}
        else:
            records[name] = {"status": "missing"}
    return records


def frame_fingerprint(frame: pd.DataFrame) -> str:
    """Content hash of a DataFrame, stable across cache serialization formats."""
    hashed = pd.util.hash_pandas_object(frame, index=True).to_numpy().tobytes()
    columns = json.dumps([str(column) for column in frame.columns]).encode()
    return _sha256(columns + hashed)[:16]


def source_snapshots(cache: Cache) -> dict[str, Any]:
    """Identify every cached source frame a run read, plus one combined fingerprint."""
    snapshots = []
    for key in cache.accessed_keys():
        info = cache.entry_info(key)
        frame = cache.get(key)
        if info is None or frame is None:
            snapshots.append({"key": key, "status": "missing"})
            continue
        snapshots.append(
            {
                "key": key,
                "fetched_at": info["fetched_at"],
                "rows": info["rows"],
                "fingerprint": frame_fingerprint(frame),
            }
        )
    combined = json.dumps(
        [(s["key"], s.get("fingerprint")) for s in snapshots], sort_keys=True
    ).encode()
    return {
        "status": "recorded",
        "fingerprint": _sha256(combined)[:16],
        "count": len(snapshots),
        "snapshots": snapshots,
    }


def load_manifest(path: Path = MANIFEST_PATH) -> dict[str, Any] | None:
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


def _empty_manifest() -> dict[str, Any]:
    return {"schema_version": SCHEMA_VERSION, "updated_at": None, "runs": {}}


def record_run(
    run: str,
    *,
    configuration: dict[str, Any],
    data: dict[str, Any],
    models: dict[str, str],
    metrics: dict[str, Any],
    sources: dict[str, Any],
    models_dir: Path = MODELS_DIR,
    path: Path = MANIFEST_PATH,
    command: list[str] | None = None,
    recorded_at: str | None = None,
    code: dict[str, Any] | None = None,
    features: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Write one run's section into the manifest, keeping the other runs' sections."""
    if run not in RUN_ARTIFACTS:
        raise KeyError(f"unknown manifest run {run!r}")
    manifest = load_manifest(path) or _empty_manifest()
    now = recorded_at or datetime.now(UTC).isoformat(timespec="seconds")
    manifest["schema_version"] = SCHEMA_VERSION
    manifest["updated_at"] = now
    manifest.setdefault("runs", {})[run] = {
        "recorded_at": now,
        "command": " ".join(command if command is not None else ["python", *sys.argv]),
        "code": code if code is not None else code_identity(),
        "configuration": configuration,
        "data": data,
        "feature_schema": (features or feature_schema()) if run == "train" else None,
        "models": models,
        "sources": sources,
        "artifacts": artifact_records(RUN_ARTIFACTS[run], models_dir),
        "metrics": metrics,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return manifest


def verify_artifacts(
    manifest: dict[str, Any] | None, models_dir: Path = MODELS_DIR
) -> dict[str, Any]:
    """Compare recorded hashes with the artifacts present where serving loads them."""
    if manifest is None:
        return {"status": "manifest_missing", "artifacts": {}}
    results: dict[str, str] = {}
    for run in manifest.get("runs", {}).values():
        for name, recorded in run.get("artifacts", {}).items():
            path = models_dir / name
            if "sha256" not in recorded:
                results[name] = "not_recorded"
            elif not path.exists():
                results[name] = "missing"
            else:
                matches = _sha256(path.read_bytes()) == recorded["sha256"]
                results[name] = "match" if matches else "mismatch"
    if not results:
        status = "empty"
    elif all(value == "match" for value in results.values()):
        status = "verified"
    else:
        status = "drift"
    return {"status": status, "artifacts": results}


# --- README -----------------------------------------------------------------


def _pct(value: Any) -> str:
    return f"{value * 100:.1f}%" if isinstance(value, (int, float)) else "n/a"


def _num(value: Any, digits: int = 3) -> str:
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else "n/a"


def render_readme_table(manifest: dict[str, Any] | None) -> str:
    """Markdown metrics table rendered only from the manifest; gaps say so."""
    runs = (manifest or {}).get("runs", {})
    rows = ["| Model | Version | Evaluation | Result | Baseline |", "|---|---|---|---|---|"]
    train = runs.get("train")
    if train:
        holdout = train["data"].get("holdout_season")
        outcome = train["metrics"].get("outcome", {})
        points = train["metrics"].get("points", {})
        rows.append(
            f"| Game outcome | `{train['models'].get('outcome')}` | temporal holdout {holdout} "
            f"({outcome.get('n_games', 'n/a')} games) | {_pct(outcome.get('accuracy'))} accuracy, "
            f"log loss {_num(outcome.get('log_loss'))} | "
            f"{_pct(outcome.get('baseline_accuracy'))} / {_num(outcome.get('baseline_log_loss'))}"
            " (always pick home) |"
        )
        rows.append(
            f"| Player points | `{train['models'].get('player_points')}` | temporal holdout "
            f"{holdout} ({points.get('n_games', 'n/a')} player-games) | MAE "
            f"{_num(points.get('mae'), 2)}; 80% interval covered "
            f"{_pct(points.get('interval_coverage'))} | MAE {_num(points.get('baseline_mae'), 2)}"
            " (10-game average) |"
        )
    else:
        rows.append("| Game outcome / player points | — | not recorded | — | — |")
    season = runs.get("season_backtest")
    if season:
        metrics = season["metrics"]
        record = metrics.get("record", {})
        playoffs = metrics.get("playoffs", {})
        seasons = ", ".join(metrics.get("seasons", []))
        rows.append(
            f"| Season forecast | `{season['models'].get('season_forecast')}` | backtest {seasons} "
            f"({metrics.get('team_seasons', 'n/a')} team-seasons) | win MAE "
            f"{_num(record.get('mae'), 2)}; playoff Brier {_num(playoffs.get('brier'))} | "
            f"MAE {_num(record.get('baseline_mae'), 2)}; Brier "
            f"{_num(playoffs.get('baseline_brier'))} |"
        )
    else:
        rows.append("| Season forecast | — | not recorded | — | — |")
    player = runs.get("player_backtest")
    if player:
        metrics = player["metrics"]
        rows.append(
            f"| Player season | `{player['models'].get('player_season')}` | stable-roster holdout "
            f"{player['data'].get('holdout_season')} ({metrics.get('players', 'n/a')} players) | "
            f"PTS MAE {_num(metrics.get('pts_mae'), 2)}; interval covered "
            f"{_pct(metrics.get('pts_interval_coverage'))} | none recorded |"
        )
    else:
        rows.append("| Player season | — | not recorded | — | — |")
    rows.append(
        "| Starting five / game simulator | "
        f"`{MODEL_VERSIONS['lineup']}` / `{MODEL_VERSIONS['score_simulator']}` | "
        "no holdout recorded | heuristic blend / distribution diagnostic | — |"
    )
    updated = (manifest or {}).get("updated_at") or "never"
    footer = (
        f"\nRecorded in [`models/manifest.json`](models/manifest.json) (updated {updated}), "
        "including code revision, data cutoffs, source fingerprints, and artifact hashes."
    )
    return "\n".join(rows) + "\n" + footer


def sync_readme(readme: Path, manifest: dict[str, Any] | None, *, check: bool = False) -> bool:
    """Replace the generated block; with ``check`` only report whether it is current."""
    text = readme.read_text()
    start, end = text.find(README_START), text.find(README_END)
    if start < 0 or end < start:
        raise ValueError(f"{readme} has no generated model-metrics block")
    block = f"{README_START}\n{render_readme_table(manifest)}\n{README_END}"
    updated = text[:start] + block + text[end + len(README_END) :]
    if check:
        return updated == text
    readme.write_text(updated)
    return True


# --- backfill -----------------------------------------------------------------

_NOT_RECORDED = {
    "status": "not_recorded",
    "reason": "artifact produced before manifest tracking; rerun the command to record sources",
}


def backfill(models_dir: Path = MODELS_DIR, path: Path = MANIFEST_PATH) -> dict[str, Any]:
    """Record artifacts that already exist, marking unknown provenance explicitly."""
    manifest: dict[str, Any] = load_manifest(path) or _empty_manifest()

    def read(name: str) -> dict[str, Any] | None:
        try:
            return json.loads((models_dir / name).read_text())
        except (OSError, ValueError):
            return None

    unknown_code = {"package_version": None, "git_commit": None, "git_dirty": None}
    trained = read("metrics.json")
    if trained:
        manifest = record_run(
            "train",
            configuration={
                "train_seasons": len(trained.get("train_seasons", [])),
                "outcome_C": trained.get("outcome", {}).get("C"),
            },
            data={
                "train_seasons": trained.get("train_seasons"),
                "dev_season": trained.get("dev_season"),
                "holdout_season": trained.get("holdout_season"),
            },
            models={k: MODEL_VERSIONS[k] for k in ("outcome", "player_points", "lineup")},
            metrics={
                "outcome": trained.get("outcome", {}),
                "points": trained.get("points", {}),
                "win_curve_slope": trained.get("win_curve_slope"),
            },
            sources=_NOT_RECORDED,
            models_dir=models_dir,
            path=path,
            command=["backfill", "python -m nba_insights.ml.train"],
            recorded_at=trained.get("trained_at"),
            code=unknown_code,
            features=artifact_feature_schema(models_dir),
        )
    season = read("season_forecast_metrics.json")
    if season:
        manifest = record_run(
            "season_backtest",
            configuration={"n_sims_per_season": season.get("n_sims_per_season")},
            data={
                "seasons": season.get("metrics", {}).get("seasons"),
                "data_cutoffs": season.get("data_cutoffs"),
                "forecast_timing": season.get("forecast_timing"),
            },
            models={"season_forecast": season.get("version", MODEL_VERSIONS["season_forecast"])},
            metrics=season.get("metrics", {}),
            sources=_NOT_RECORDED,
            models_dir=models_dir,
            path=path,
            command=["backfill", "python -m nba_insights.ml.backtest"],
            recorded_at=season.get("generated_at"),
            code=unknown_code,
        )
    player = read("player_season_metrics.json")
    if player:
        manifest = record_run(
            "player_backtest",
            configuration={},
            data={
                "source_season": player.get("source_season"),
                "holdout_season": player.get("holdout_season"),
                "population": player.get("population"),
            },
            models={"player_season": player.get("version", MODEL_VERSIONS["player_season"])},
            metrics=player.get("metrics", {}),
            sources=_NOT_RECORDED,
            models_dir=models_dir,
            path=path,
            command=["backfill", "python -m nba_insights.ml.player_backtest"],
            recorded_at=player.get("generated_at"),
            code=unknown_code,
        )
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser("backfill", help="record artifacts already in the models directory")
    readme = sub.add_parser("readme", help="render the README metrics table")
    readme.add_argument("--check", action="store_true", help="fail if the README is stale")
    readme.add_argument("--path", type=Path, default=Path("README.md"))
    args = parser.parse_args()
    if args.action == "backfill":
        manifest = backfill()
        print(json.dumps(verify_artifacts(manifest), indent=2))
        return
    current = sync_readme(args.path, load_manifest(), check=args.check)
    if args.check and not current:
        sys.exit(f"{args.path} metrics table is stale: run `{README_COMMAND}`")


if __name__ == "__main__":
    main()
